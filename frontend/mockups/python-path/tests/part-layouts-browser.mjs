import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'
import { slidingWindowSteps as steps, originalSlidingWindowProblem as original } from '../content/blind75Practice.js'
import { STORAGE_KEY, blankProgress } from '../progress.js'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE ?? '@playwright/test')
const base = process.env.SAMPLE_BASE_URL ?? 'http://127.0.0.1:4319/'
const browser = await chromium.launch({ headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] })
  await context.addInitScript(({ key, progress, selectedId }) => {
    if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ kind: 'python-path', version: 1, selectedId, drafts: { assign: { 'main.py': '# saved basics draft' } }, notes: {}, progress }))
  }, { key: STORAGE_KEY, progress: blankProgress(), selectedId: 'assign' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}?sample=sliding-window`, { waitUntil: 'networkidle' })
  const panel = page.locator('#site-panel-practice')
  const prompt = panel.getByRole('region', { name: 'Exercise instructions', exact: true })
  const originalCard = prompt.getByRole('region', { name: 'Original problem', exact: true })
  const nav = prompt.getByRole('navigation', { name: 'Question parts', exact: true })
  const trigger = nav.locator('button[aria-expanded]')
  const options = nav.getByRole('group', { name: 'Available parts', exact: true })
  const task = prompt.getByRole('region', { name: 'Your task', exact: true })
  const editor = panel.getByRole('region', { name: 'Code workspace', exact: true })
  await originalCard.getByText(original.statement, { exact: true }).waitFor()
  assert.equal(await originalCard.getByRole('link').getAttribute('href'), original.source)
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
  assert.equal(await options.isVisible(), false)
  assert.equal(await panel.getByRole('group', { name: 'Part navigation demos', exact: true }).count(), 0)
  const order = await prompt.evaluate(element => {
    const original = element.querySelector('[aria-label="Original problem"]')
    const nav = element.querySelector('[aria-label="Question parts"]')
    const task = element.querySelector('[aria-label="Your task"]')
    return !!(original.compareDocumentPosition(task) & Node.DOCUMENT_POSITION_FOLLOWING) && task.contains(nav)
  })
  assert.equal(order, true, 'Original problem precedes one task card containing its part selector')
  await page.waitForFunction(() => [...document.querySelectorAll('#site-panel-practice button')].some(button => button.textContent.trim() === 'Run code' && !button.disabled), null, { timeout: 65000 })
  const originalText = await originalCard.textContent()
  async function choosePart(index) {
    await trigger.click()
    await options.waitFor()
    assert.equal(await options.getByRole('button').count(), steps.length)
    await options.getByRole('button', { name: steps[index].title, exact: true }).click()
    await options.waitFor({ state: 'hidden' })
    await task.getByText(steps[index].prompt, { exact: true }).waitFor()
    assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
    assert.equal(await originalCard.textContent(), originalText)
  }
  async function shot(name, fullPage = false) { await page.screenshot({ path: fileURLToPath(new URL(`../.cache/${name}.png`, import.meta.url)), fullPage }) }
  await shot('outline-dropdown-original')
  for (const index of [1, 3, 2, 0]) await choosePart(index)
  assert.ok(await prompt.evaluate(element => element.scrollTop > 0), 'Part changes keep the selector/task in view')
  await shot('outline-dropdown-task')
  await trigger.focus()
  await page.keyboard.press('Enter')
  await options.waitFor()
  await page.keyboard.press('Escape')
  await options.waitFor({ state: 'hidden' })
  assert.equal(await trigger.evaluate(element => document.activeElement === element), true)
  await choosePart(1)
  await editor.locator('.monaco-editor').click()
  await page.keyboard.press('ControlOrMeta+A')
  const code = steps[1].solutionFiles['main.py']
  await page.evaluate(value => navigator.clipboard.writeText(value), code)
  await page.keyboard.press('ControlOrMeta+V')
  await page.waitForFunction(({ key, id, code }) => JSON.parse(localStorage.getItem(key) ?? '{}').drafts?.[id]?.['main.py']?.trim() === code.trim(), { key: STORAGE_KEY, id: steps[1].id, code })
  await editor.getByRole('button', { name: 'Run code', exact: true }).click()
  await panel.getByText('That works. Nice rep.', { exact: true }).waitFor()
  await editor.getByRole('button', { name: /^Next part/ }).click()
  await task.getByText(steps[2].prompt, { exact: true }).waitFor()
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
  await choosePart(1)
  await page.reload({ waitUntil: 'networkidle' })
  await originalCard.getByText(original.statement, { exact: true }).waitFor()
  await task.getByText(steps[1].prompt, { exact: true }).waitFor()
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false')
  const library = panel.getByRole('region', { name: 'Full questions list', exact: true })
  const actualPatterns = await library.locator('.MuiAccordionSummary-content').evaluateAll(items => items.map(item => item.firstElementChild.textContent))
  assert.deepEqual(actualPatterns, ['Array scans and running state', 'Sets and dictionaries', 'Stacks', 'Two pointers and palindrome expansion', 'Sliding Window', 'Binary search', 'Intervals', 'Matrices', 'Linked structures', 'Trees and BSTs', 'Heaps', 'Graphs', 'Backtracking and tries', 'Bits', 'DP and greedy reasoning'])
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), STORAGE_KEY)
  assert.equal(saved.drafts.assign['main.py'], '# saved basics draft')
  assert.equal(saved.drafts[steps[1].id]['main.py'].trim(), code.trim())
  await page.setViewportSize({ width: 390, height: 844 })
  await choosePart(3)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await shot('outline-dropdown-mobile', true)
  await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).click()
  await shot('outline-dropdown-dark', true)
  assert.equal(await originalCard.textContent(), originalText)
  assert.deepEqual(errors, [])
  await context.close()
  console.log('PASS: combined task/selector, cumulative pattern ordering, original-first sequence, outline-style dropdown, selection closes list, all part counts, keyboard Escape, task scroll position, real code/Next part, draft reload, mobile and dark mode.')
} finally { await browser.close() }
