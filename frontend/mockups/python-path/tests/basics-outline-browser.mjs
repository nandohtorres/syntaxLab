import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
import { STORAGE_KEY } from '../progress.js'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE ?? '@playwright/test')
const base = process.env.SAMPLE_BASE_URL ?? 'http://127.0.0.1:4319/'
const browser = await chromium.launch({ headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}?sample=sliding-window#python`, { waitUntil: 'networkidle' })
  const panel = page.locator('#site-panel-python')
  const prompt = panel.getByRole('region', { name: 'Exercise instructions', exact: true })
  const nav = prompt.getByRole('navigation', { name: 'Question parts', exact: true })
  const trigger = nav.locator('button[aria-expanded]')
  const options = nav.getByRole('group', { name: 'Available parts', exact: true })
  const variants = prompt.getByRole('group', { name: 'Practice variations', exact: true })
  await prompt.getByRole('heading', { name: 'Start a Python program', exact: true }).waitFor()
  await trigger.click()
  assert.equal(await options.getByRole('button').count(), 2, 'Two skills, not six repeated titles')
  await options.getByRole('button', { name: 'a. Create an integer variable', exact: true }).click()
  await options.waitFor({ state: 'hidden' })
  assert.equal(await variants.getByRole('button').count(), 3)
  await variants.getByRole('button', { name: 'Variation 2 of 3', exact: true }).click()
  assert.equal(await variants.getByRole('button', { name: 'Variation 2 of 3', exact: true }).getAttribute('aria-pressed'), 'true')
  await panel.locator('.monaco-editor').waitFor()
  const draft = '# preserved variation two\nretries = 4'
  await panel.locator('.monaco-editor').click()
  await page.keyboard.press('ControlOrMeta+A')
  await page.evaluate(code => navigator.clipboard.writeText(code), draft)
  await page.keyboard.press('ControlOrMeta+V')
  await variants.getByRole('button', { name: 'Variation 1 of 3', exact: true }).click()
  await variants.getByRole('button', { name: 'Variation 2 of 3', exact: true }).click()
  await page.waitForFunction(({ key, draft }) => JSON.parse(localStorage.getItem(key) ?? '{}').drafts?.['assign-v1']?.['main.py']?.trim() === draft.trim(), { key: STORAGE_KEY, draft })
  await trigger.click()
  await options.getByRole('button', { name: 'b. Print text', exact: true }).click()
  await options.waitFor({ state: 'hidden' })
  await prompt.getByRole('heading', { name: 'Start a Python program', exact: true }).waitFor()
  assert.equal(await variants.getByRole('button', { name: 'Variation 1 of 3', exact: true }).getAttribute('aria-pressed'), 'true')
  const state = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), STORAGE_KEY)
  assert.equal(state.progress.attempts.length, 0, 'Choosing parts/variations never earns progress')
  await prompt.screenshot({ path: fileURLToPath(new URL('../.cache/basics-outline-desktop.png', import.meta.url)) })

  const library = panel.getByRole('region', { name: 'Full questions list', exact: true })
  await library.getByRole('button', { name: /Variables and types/ }).click()
  await library.getByRole('button').filter({ hasText: 'Create a string' }).first().click()
  await prompt.getByRole('heading', { name: 'Variables and types', exact: true }).waitFor()
  await trigger.click()
  assert.equal(await options.getByRole('button').count(), 6, 'Six skills with their existing variations retained')
  await page.keyboard.press('Escape')
  await options.waitFor({ state: 'hidden' })
  await panel.getByRole('button', { name: 'Change practice order', exact: true }).click()
  await panel.getByText('Mixed: current unit', { exact: true }).waitFor()

  await library.getByRole('button', { name: /Summarize an inventory/ }).click()
  await library.getByRole('button').filter({ hasText: 'Summarize a service inventory' }).click()
  await prompt.getByRole('heading', { name: 'Summarize an inventory', exact: true }).waitFor()
  assert.equal(await variants.count(), 0, 'Single-exercise topics do not show a variation control')
  await page.setViewportSize({ width: 390, height: 844 })
  await trigger.click()
  assert.equal(await options.getByRole('button').count(), 1)
  await page.keyboard.press('Escape')
  await options.waitFor({ state: 'hidden' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await prompt.screenshot({ path: fileURLToPath(new URL('../.cache/basics-outline-mobile.png', import.meta.url)) })
  assert.deepEqual(errors, [])
  await context.close()
  console.log('PASS: topic headings, unique lettered skills, preserved variation drafts, no navigation credit, variable/single-part topic counts, mixed mode, keyboard and mobile layout.')
} finally { await browser.close() }
